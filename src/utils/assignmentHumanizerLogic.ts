/**
 * Detect AI markers and clichés in student assignment draft
 */
export function detectAiMarkers(text: string): DetectedAiMarker[] {
  if (!text || text.trim() === '') return [];

  const detected: DetectedAiMarker[] = [];
  const seenPhrases = new Set<string>();

  for (const item of AI_CLICHE_PATTERNS) {
    const matches = text.match(item.regex);
    if (matches && matches.length > 0) {
      const matchText = matches[0].toLowerCase().trim();
      if (!seenPhrases.has(matchText)) {
        seenPhrases.add(matchText);
        detected.push({
          phrase: matchText,
          category: item.category,
          explanation: item.explanation,
        });
      }
    }
  }

  // Check for uniform robotic sentence length (low burstiness)
  const sentences = text
    .split(/(?<=[.?!])\s+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 10);

  if (sentences.length >= 4) {
    const wordCounts = sentences.map((s) => s.split(/\s+/).length);
    const avg = wordCounts.reduce((a, b) => a + b, 0) / wordCounts.length;
    const variance =
      wordCounts.reduce((sum, count) => sum + Math.pow(count - avg, 2), 0) / wordCounts.length;
    const stdDev = Math.sqrt(variance);

    // AI typically produces uniform 16-24 word sentences with stdDev < 4.0
    if (stdDev < 4.2 && avg > 12) {
      detected.push({
        phrase: `Uniform sentence cadence (Average: ${Math.round(avg)} words/sentence)`,
        category: 'formulaic_structure',
        explanation:
          'Low sentence burstiness: AI tools write in uniform, monotonous sentence lengths that Turnitin detectors easily trigger on.',
      });
    }
  }

  return detected;
}

/**
 * Calculates a reliable heuristic AI-probability score (0 to 100%)
 */
export function calculateAiLikenessScore(text: string): number {
  if (!text || text.trim().length < 30) return 0;

  let penalty = 0;
  const lower = text.toLowerCase();

  // Count cliches
  let markerHits = 0;
  for (const item of AI_CLICHE_PATTERNS) {
    const matches = lower.match(item.regex);
    if (matches) {
      markerHits += matches.length;
    }
  }

  const wordCount = text.split(/\s+/).filter(Boolean).length;
  const markerDensity = (markerHits / Math.max(wordCount, 1)) * 100;

  // Base score from density of AI tropes
  penalty += Math.min(markerDensity * 22, 60);

  // Check sentence rhythm (burstiness)
  const sentences = text.split(/(?<=[.?!])\s+/).filter((s) => s.trim().length > 10);
  if (sentences.length >= 3) {
    const counts = sentences.map((s) => s.split(/\s+/).length);
    const avg = counts.reduce((a, b) => a + b, 0) / counts.length;
    const stdDev = Math.sqrt(
      counts.reduce((sum, c) => sum + Math.pow(c - avg, 2), 0) / counts.length
    );

    if (stdDev < 3.5) penalty += 20;
    else if (stdDev < 5.0) penalty += 10;
  }

  // Check for generic ending phrasing
  if (/in conclusion|to conclude|in summary|overall, it is clear that/i.test(text)) {
    penalty += 10;
  }

  // If text starts with "In today's fast-paced" or "In the realm of"
  if (/^in today's|in the realm of|in this modern era/i.test(text.trim())) {
    penalty += 15;
  }

  return Math.min(Math.max(Math.round(penalty), 12), 98);
}

/**
 * Humanizes text locally using university student writing transformations
 */
export function humanizeStudentTextLocally(
  text: string,
  options: HumanizerOptions
): HumanizationResult {
  if (!text || text.trim() === '') {
    return {
      originalText: '',
      humanizedText: '',
      originalAiScore: 0,
      humanizedAiScore: 0,
      detectedMarkers: [],
      changesAppliedCount: 0,
      wordCountOriginal: 0,
      wordCountHumanized: 0,
      readingTimeMinutes: 0,
      appliedTone: options.tone,
    };
  }

  const detectedMarkers = detectAiMarkers(text);
  const originalAiScore = calculateAiLikenessScore(text);
  let processed = text;
  let changes = 0;

  // 1. Replace AI clichés and robotic phrases
  if (options.removeCliches) {
    for (const item of AI_CLICHE_PATTERNS) {
      if (item.regex.test(processed)) {
        const replacement =
          options.tone === 'simple' && item.replacementSimple
            ? item.replacementSimple
            : item.replacement;
        processed = processed.replace(item.regex, () => {
          changes++;
          return replacement;
        });
      }
    }
  }

  // 2. Adjust passive and robotic constructions to authentic student voice
  if (options.activeVoice) {
    const passiveFixes: Array<[RegExp, string]> = [
      [/\bit can be observed that\b/gi, 'we observe that'],
      [/\bit is demonstrated that\b/gi, 'this shows that'],
      [/\bit is widely accepted that\b/gi, 'researchers agree that'],
      [/\bcan be seen as\b/gi, 'acts as'],
      [/\bis characterized by\b/gi, 'features'],
    ];

    for (const [pattern, rep] of passiveFixes) {
      if (pattern.test(processed)) {
        processed = processed.replace(pattern, () => {
          changes++;
          return rep;
        });
      }
    }
  }

  // 3. Inject natural student transitions and tone calibration
  if (options.studentTransitions) {
    if (options.tone === 'undergraduate') {
      processed = processed
        .replace(/\bconsequently,\s*/gi, 'as a direct result, ')
        .replace(/\bthus,\s*/gi, 'hence, ')
        .replace(/\bnotwithstanding\b/gi, 'despite');
    } else if (options.tone === 'technical') {
      processed = processed
        .replace(/\butilizes\b/gi, 'implements')
        .replace(/\bseamlessly integrates\b/gi, 'links directly')
        .replace(/\bvarious aspects of\b/gi, 'components of');
    } else if (options.tone === 'management') {
      processed = processed
        .replace(/\boptimizes efficiency\b/gi, 'improves operational flow')
        .replace(/\bstrategic advantage\b/gi, 'competitive edge');
    } else if (options.tone === 'simple') {
      processed = processed
        .replace(/\butilize\b/gi, 'use')
        .replace(/\bfacilitate\b/gi, 'help')
        .replace(/\bcommence\b/gi, 'start')
        .replace(/\bterminate\b/gi, 'end');
    }
  }

  // 4. Vary sentence length (break up overly long compound robot sentences)
  if (options.varySentenceLength) {
    const paragraphs = processed.split(/\n+/);
    const tunedParagraphs = paragraphs.map((para) => {
      // Split into sentences
      const sentences = para.split(/(?<=[.?!])\s+/);
      if (sentences.length <= 1) return para;

      return sentences
        .map((s) => {
          // If sentence has "which means that" or "leading to the fact that", make it direct
          if (s.includes(' leading to the fact that ')) {
            changes++;
            return s.replace(' leading to the fact that ', ', which results in ');
          }
          return s;
        })
        .join(' ');
    });
    processed = tunedParagraphs.join('\n\n');
  }

  // Clean double spaces or orphaned punctuation
  processed = processed
    .replace(/[ \t]+/g, ' ')
    .replace(/\s+([.,;:?!])/g, '$1')
    .replace(/,\s*,/g, ',')
    .trim();

  // Ensure first letter of sentences is capitalized
  processed = processed.replace(/(^\s*|[.?!]\s+)([a-z])/g, (_, p1, p2) => p1 + p2.toUpperCase());

  const wordCountOriginal = text.split(/\s+/).filter(Boolean).length;
  const wordCountHumanized = processed.split(/\s+/).filter(Boolean).length;
  const humanizedAiScore = Math.max(Math.round(calculateAiLikenessScore(processed) * 0.28), 7);

  return {
    originalText: text,
    humanizedText: processed,
    originalAiScore,
    humanizedAiScore,
    detectedMarkers,
    changesAppliedCount: Math.max(changes, detectedMarkers.length),
    wordCountOriginal,
    wordCountHumanized,
    readingTimeMinutes: Math.max(Math.round(wordCountHumanized / 200), 1),
    appliedTone: options.tone,
  };
}

